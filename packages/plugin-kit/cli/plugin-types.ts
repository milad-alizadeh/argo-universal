import { readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { PluginManifest } from '@repo/contracts/plugins';
import type { OperationDeclaration } from '@repo/contracts/plugins/operations-api';
import type { PluginOperationContribution } from '@repo/contracts/plugins/plugin-operations';
import type { PluginValidation } from '@repo/engine/plugin-validation';
import { readPluginManifest } from '@repo/engine/plugins';

/*
 * `plugin.gen.d.ts`: the manifest's Operations as types, beside `plugin.json`. Importing the JSON would
 * widen every name and choice to `string`, so `argo-plugin types` writes them out as literals and merges
 * them into the kit's `PluginOperations`. A Plugin that declares no Operations has no such file.
 */
const pluginTypesFile = 'plugin.gen.d.ts';

// What the types read of one Operation: each param's type, whether it is required, its choices; and its needs.
const declaration = ({
  params = {},
  caller,
}: PluginOperationContribution): OperationDeclaration => ({
  params: Object.fromEntries(
    Object.entries(params).map(([name, { type, required, choices }]) => [
      name,
      { type, required, choices },
    ]),
  ),
  caller,
});

// JSON is a TypeScript type literal too: its strings, booleans and arrays read as literals and tuples.
const member = (operation: PluginOperationContribution): string =>
  `    ${operation.name}: ${JSON.stringify(declaration(operation), null, 2).replaceAll('\n', '\n    ')};`;

// What `plugin.gen.d.ts` holds for this manifest, or null when it declares no Operations.
function pluginTypes(manifest: PluginManifest): string | null {
  const operations = manifest.contributes.operations ?? [];

  if (!operations.length) return null;

  return [
    `// Generated by \`argo-plugin types\` from plugin.json; run it again after changing the manifest's Operations.`,
    'export {};',
    '',
    "declare module '@argo/plugin-kit' {",
    '  interface PluginOperations {',
    ...operations.map(member),
    '  }',
    '}',
    '',
  ].join('\n');
}

const written = (path: string): Promise<string | null> =>
  readFile(path, 'utf8').catch(() => null);

// Why the file on disk is not what the manifest makes, or null when it is.
async function typesProblem(
  directory: string,
  manifest: PluginManifest,
): Promise<string | null> {
  const expected = pluginTypes(manifest);
  const actual = await written(join(directory, pluginTypesFile));

  if (actual === expected) return null;

  return expected === null
    ? `${pluginTypesFile} declares Operations plugin.json no longer has. Run argo-plugin types.`
    : `${pluginTypesFile} is missing or stale. Run argo-plugin types.`;
}

// `validate` fails while the types are not the manifest's, or the type check reads Operations the Plugin lacks.
export async function typesDiagnostics(
  directory: string,
  manifest: PluginManifest,
): Promise<PluginValidation['diagnostics']> {
  const problem = await typesProblem(directory, manifest);
  const file = join(directory, pluginTypesFile);

  return problem ? [{ file, line: 1, column: 1, message: problem }] : [];
}

/*
 * `argo-plugin types <dir>` writes the manifest's file, or removes one left from Operations it no longer
 * declares; with `--check` it writes nothing and fails while the file is not the manifest's.
 */
export async function types(
  directory: string,
  write: (line: string) => void,
  check: boolean,
): Promise<number> {
  const manifest = await readPluginManifest(directory, '0.0.0');

  if (check) return checked(await typesProblem(directory, manifest), write);

  await writeTypes(directory, pluginTypes(manifest));
  write(`Wrote the Operation types for ${directory}`);

  return 0;
}

function checked(
  problem: string | null,
  write: (line: string) => void,
): number {
  if (problem) write(problem);

  return Number(problem !== null);
}

const writeTypes = (directory: string, types: string | null): Promise<void> =>
  types === null
    ? rm(join(directory, pluginTypesFile), { force: true })
    : writeFile(join(directory, pluginTypesFile), types);
